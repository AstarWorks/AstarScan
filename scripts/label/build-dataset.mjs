#!/usr/bin/env bun
/**
 * Package the click-labeled corners into an Ultralytics YOLOv8-pose
 * dataset and zip it for Colab.
 *
 * Input:
 *   scripts/dataset/annotations.json   (source of truth, from server.mjs)
 *   scripts/dataset/raw/*.jpg
 * Output:
 *   scripts/dataset/yolo/
 *     data.yaml
 *     images/{train,val}/*.jpg
 *     labels/{train,val}/*.txt
 *   scripts/dataset/doc-corners-dataset.zip   (or .tgz fallback)
 *
 * Run:  bun scripts/label/build-dataset.mjs
 *
 * Split is deterministic: every 10th labeled frame (sorted by name) goes
 * to val (~10%), the rest to train. Skipped/unlabeled frames are dropped.
 */

import fs from 'node:fs/promises'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { Canvas, loadImage } from '@napi-rs/canvas'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(__dirname, '../..')
const DATASET_DIR = path.join(REPO_ROOT, 'scripts/dataset')
const RAW_DIR = path.join(DATASET_DIR, 'raw')
const ANNOT_PATH = path.join(DATASET_DIR, 'annotations.json')
const OUT_DIR = path.join(DATASET_DIR, 'yolo')

function toYoloLine(points) {
  const clamp01 = (v) => Math.min(1, Math.max(0, v))
  const xs = points.map((p) => p[0])
  const ys = points.map((p) => p[1])
  const minX = Math.min(...xs)
  const maxX = Math.max(...xs)
  const minY = Math.min(...ys)
  const maxY = Math.max(...ys)
  const cx = clamp01((minX + maxX) / 2)
  const cy = clamp01((minY + maxY) / 2)
  const w = clamp01(Math.max(1e-4, maxX - minX))
  const h = clamp01(Math.max(1e-4, maxY - minY))
  // v = 2 visible, 1 occluded(but-located). We intentionally NEVER emit
  // v=0: in Ultralytics pose loss v=0 drops the location term, so the
  // model would not learn an occluded corner's position — exactly the
  // hand-occlusion case we need it to extrapolate. Skip a frame instead
  // of marking a corner v=0.
  const kp = points
    .map((p) => `${clamp01(p[0]).toFixed(6)} ${clamp01(p[1]).toFixed(6)} ${p[2] ? 1 : 2}`)
    .join(' ')
  return `0 ${cx.toFixed(6)} ${cy.toFixed(6)} ${w.toFixed(6)} ${h.toFixed(6)} ${kp}`
}

const DATA_YAML = `# Generated by scripts/label/build-dataset.mjs — do not edit by hand.
# In Colab, set 'path' to the extracted absolute dir (see
# docs/training-doc-corners.md), then run yolo train.
path: .
train: images/train
val: images/val
kpt_shape: [4, 3]
# horizontal-flip keypoint remap so flip augmentation keeps corner identity:
#   tl<->tr (0<->1), br<->bl (2<->3)
flip_idx: [1, 0, 3, 2]
names:
  0: document
`

// ---------------------------------------------------------------------------
// Dedup-aware split. Consecutive video frames are near-identical, so a naive
// "every Nth frame → val" leaks near-copies of train into val and makes val
// mAP falsely optimistic (it hides overfitting). We hash each frame, union
// near-duplicates into one "scene" group, and split by GROUP so val holds
// only scenes the model never trained on.
// ---------------------------------------------------------------------------

const DUP_HAMMING = 8 // ≤ this 64-bit Hamming distance → same scene
const VAL_EVERY = 8 // every 8th distinct group → val (~12 %)
const PHASH_SIZE = 8

async function phash(file) {
  const img = await loadImage(path.join(RAW_DIR, file))
  const c = new Canvas(PHASH_SIZE, PHASH_SIZE)
  const ctx = c.getContext('2d')
  ctx.drawImage(img, 0, 0, PHASH_SIZE, PHASH_SIZE)
  const d = ctx.getImageData(0, 0, PHASH_SIZE, PHASH_SIZE).data
  const n = PHASH_SIZE * PHASH_SIZE
  const g = new Float64Array(n)
  let sum = 0
  for (let i = 0, j = 0; j < n; i += 4, j += 1) {
    const v = 0.2126 * d[i] + 0.7152 * d[i + 1] + 0.0722 * d[i + 2]
    g[j] = v
    sum += v
  }
  const mean = sum / n
  let h = 0n
  for (let j = 0; j < n; j += 1) if (g[j] > mean) h |= 1n << BigInt(j)
  return h
}

function hamming(a, b) {
  let x = a ^ b
  let n = 0
  while (x) {
    n += Number(x & 1n)
    x >>= 1n
  }
  return n
}

/** Union-find: frames within `thr` Hamming join one group. Returns
 *  groupOf[i] = representative index for frame i. */
function groupByHash(hashes, thr) {
  const n = hashes.length
  const parent = Array.from({ length: n }, (_, i) => i)
  const find = (i) => (parent[i] === i ? i : (parent[i] = find(parent[i])))
  for (let i = 0; i < n; i += 1) {
    for (let j = i + 1; j < n; j += 1) {
      if (hamming(hashes[i], hashes[j]) <= thr) {
        const a = find(i)
        const b = find(j)
        if (a !== b) parent[a] = b
      }
    }
  }
  return parent.map((_, i) => find(i))
}

async function main() {
  let annots
  try {
    annots = JSON.parse(await fs.readFile(ANNOT_PATH, 'utf8'))
  } catch {
    console.error(`[build] no annotations at ${path.relative(REPO_ROOT, ANNOT_PATH)} — run the labeler first:`)
    console.error('         bun scripts/label/server.mjs')
    process.exit(1)
  }

  const files = Object.keys(annots).sort()
  const labeled = files.filter((f) => annots[f] && !annots[f].skipped && Array.isArray(annots[f].points) && annots[f].points.length === 4)
  const skipped = files.filter((f) => annots[f] && annots[f].skipped)
  const allRaw = (await fs.readdir(RAW_DIR)).filter((f) => /\.(jpe?g|png)$/i.test(f))
  const unlabeled = allRaw.length - labeled.length - skipped.length

  if (labeled.length === 0) {
    console.error('[build] no completed labels yet — nothing to package.')
    process.exit(1)
  }

  // Fresh output tree.
  await fs.rm(OUT_DIR, { recursive: true, force: true })
  for (const split of ['train', 'val']) {
    await fs.mkdir(path.join(OUT_DIR, 'images', split), { recursive: true })
    await fs.mkdir(path.join(OUT_DIR, 'labels', split), { recursive: true })
  }

  // Dedup-aware split (see groupByHash above): hash every frame, union
  // near-duplicates into scene groups, and hold out WHOLE groups for val so
  // it shares no scene with train.
  console.log('[build] hashing frames for dedup-aware split...')
  const hashes = await Promise.all(labeled.map((f) => phash(f)))
  const groupOf = groupByHash(hashes, DUP_HAMMING)
  const orderedGroups = [...new Set(groupOf)]
    .map((g) => ({ g, first: groupOf.indexOf(g) }))
    .sort((a, b) => a.first - b.first)
    .map((x) => x.g)
  const valGroups = new Set(
    orderedGroups.filter((_, i) => i % VAL_EVERY === VAL_EVERY - 1),
  )
  if (valGroups.size === 0 && orderedGroups.length >= 2) {
    valGroups.add(orderedGroups[orderedGroups.length - 1])
  }
  const nGroups = orderedGroups.length

  let nTrain = 0
  let nVal = 0
  for (let i = 0; i < labeled.length; i += 1) {
    const file = labeled[i]
    const split = valGroups.has(groupOf[i]) ? 'val' : 'train'
    if (split === 'val') nVal += 1
    else nTrain += 1
    const base = file.replace(/\.[^.]+$/, '')
    await fs.copyFile(path.join(RAW_DIR, file), path.join(OUT_DIR, 'images', split, file))
    await fs.writeFile(
      path.join(OUT_DIR, 'labels', split, base + '.txt'),
      toYoloLine(annots[file].points) + '\n',
    )
  }

  await fs.writeFile(path.join(OUT_DIR, 'data.yaml'), DATA_YAML)

  // Zip (preferred for Colab upload); fall back to tar.gz.
  let archive = path.join(DATASET_DIR, 'doc-corners-dataset.zip')
  await fs.rm(archive, { force: true })
  let z = spawnSync('zip', ['-r', '-q', archive, 'yolo'], { cwd: DATASET_DIR })
  if (z.error || z.status !== 0) {
    archive = path.join(DATASET_DIR, 'doc-corners-dataset.tgz')
    await fs.rm(archive, { force: true })
    z = spawnSync('tar', ['czf', archive, '-C', DATASET_DIR, 'yolo'])
    if (z.error || z.status !== 0) {
      console.warn('[build] both zip and tar failed — the yolo/ folder is ready, archive it manually.')
      archive = null
    }
  }

  console.log('[build] done.')
  console.log(`  labeled=${labeled.length}  (train=${nTrain}, val=${nVal})  skipped=${skipped.length}  unlabeled=${unlabeled}`)
  console.log(`  distinct scenes (dedup groups)=${nGroups} → val is ${nVal} frames from held-out groups (no train near-dupes)`)
  console.log(`  dataset:  ${path.relative(REPO_ROOT, OUT_DIR)}/`)
  if (archive) console.log(`  archive:  ${path.relative(REPO_ROOT, archive)}  → upload to Colab/Kaggle`)
  if (unlabeled > 0) console.log(`  note: ${unlabeled} frame(s) still unlabeled — run the labeler to finish, or proceed with ${labeled.length}.`)
  if (labeled.length < 150) console.log('  warn: <150 labeled frames may underfit; aim for ~250 (see training doc).')
  if (nGroups < 25) console.log(`  warn: only ${nGroups} distinct scenes — low diversity; in-distribution val will flatter. Validate on a HELD-OUT video.`)
  console.log('  honest test: both eval mp4s are training sources — judge generalization on a held-out video (e.g. 20260516_*.mp4) via scripts/eval/run.mjs.')
}

main()
